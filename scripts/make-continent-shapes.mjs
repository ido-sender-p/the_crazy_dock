// Builds src/continentShapes.ts: one simplified outline per continent for the home page "By continent" cards.
// Source: Natural Earth 110m countries (public domain), https://www.naturalearthdata.com/
// Usage: node scripts/make-continent-shapes.mjs [path-to-ne_110m_admin_0_countries.geojson]
// (downloaded from the natural-earth-vector repository when no path is given). Output is committed, so this runs rarely.
import { readFile, writeFile } from "node:fs/promises";

const URL_NE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson";
const src = process.argv[2];
const geo = JSON.parse(src ? await readFile(src, "utf8") : await (await fetch(URL_NE)).text());

const SLUG = { "North America": "north-america", "South America": "south-america", Europe: "europe", Africa: "africa", Asia: "asia", Oceania: "oceania" };
// Russia spans two continents and would dwarf both; Greenland and the far north make North America unrecognisable at icon size.
const SKIP = new Set(["Russia", "Greenland", "Antarctica", "Fr. S. Antarctic Lands"]);
const MIN_AREA = { default: 1.2, oceania: 2.5 }; // square degrees; smaller islands are dropped
const TOLERANCE = 0.3; // degrees, Douglas-Peucker

function perpendicular(p, a, b) {
  const dx = b[0] - a[0], dy = b[1] - a[1];
  const len = Math.hypot(dx, dy);
  if (!len) return Math.hypot(p[0] - a[0], p[1] - a[1]);
  return Math.abs(dy * p[0] - dx * p[1] + b[0] * a[1] - b[1] * a[0]) / len;
}
function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  let max = 0, idx = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const d = perpendicular(pts[i], pts[0], pts.at(-1));
    if (d > max) { max = d; idx = i; }
  }
  if (max <= tol) return [pts[0], pts.at(-1)];
  return [...simplify(pts.slice(0, idx + 1), tol).slice(0, -1), ...simplify(pts.slice(idx), tol)];
}
const area = (ring) => Math.abs(ring.reduce((s, p, i) => s + (p[0] * ring[(i + 1) % ring.length][1] - ring[(i + 1) % ring.length][0] * p[1]), 0)) / 2;

const byCont = {};
for (const f of geo.features) {
  const p = f.properties;
  const slug = SLUG[p.CONTINENT];
  if (!slug || SKIP.has(p.NAME)) continue;
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) {
    let ring = poly[0].map(([x, y]) => [x, y]);
    // west-of-the-date-line pieces (Aleutians, Chukotka) and east-of-it (Fiji) are moved to the continent's main side
    const mean = ring.reduce((s, q) => s + q[0], 0) / ring.length;
    // Europe keeps the mainland and the large islands: Iceland, Svalbard and overseas pieces (French Guiana, the Azores) would stretch it
    const midY = ring.reduce((s2, q) => s2 + q[1], 0) / ring.length;
    if (slug === "europe" && !(mean > -11 && mean < 45 && midY > 34 && midY < 72)) continue;
    if (slug === "north-america" && mean > 0) continue;
    if (slug === "oceania" && mean < 0) ring = ring.map(([x, y]) => [x + 360, y]);
    if (area(ring) < (MIN_AREA[slug] ?? MIN_AREA.default)) continue;
    (byCont[slug] ??= []).push(ring);
  }
}

const out = {};
for (const [slug, rings] of Object.entries(byCont)) {
  const all = rings.flat();
  const lats = all.map((q) => q[1]);
  const midLat = (Math.min(...lats) + Math.max(...lats)) / 2;
  const k = Math.cos((midLat * Math.PI) / 180); // shrink longitude so shapes keep their proportions away from the equator
  const proj = rings.map((r) => r.map(([x, y]) => [x * k, -y]));
  const xs = proj.flat().map((q) => q[0]), ys = proj.flat().map((q) => q[1]);
  const minX = Math.min(...xs), minY = Math.min(...ys);
  const w = Math.max(...xs) - minX, h = Math.max(...ys) - minY;
  const scale = 100 / Math.max(w, h);
  const d = proj
    .map((r) => simplify(r, TOLERANCE * k).map(([x, y]) => `${((x - minX) * scale).toFixed(1)} ${((y - minY) * scale).toFixed(1)}`))
    .filter((pts) => pts.length >= 3)
    .map((pts) => "M" + pts.join("L") + "Z")
    .join("");
  out[slug] = { viewBox: `0 0 ${(w * scale).toFixed(0)} ${(h * scale).toFixed(0)}`, d };
}

const order = ["north-america", "south-america", "europe", "africa", "asia", "oceania"];
const body = order.map((s) => `  "${s}": { viewBox: "${out[s].viewBox}", d: "${out[s].d}" },`).join("\n");
await writeFile(
  new URL("../src/continentShapes.ts", import.meta.url),
  `// Generated by scripts/make-continent-shapes.mjs from Natural Earth (public domain). Do not edit by hand.\n// One simplified outline per continent, in a viewBox about 100 units on its longest side.\nexport const CONTINENT_ICONS: Record<string, { viewBox: string; d: string }> = {\n${body}\n};\n`,
);
for (const s of order) console.log(s, out[s].viewBox, out[s].d.length, "chars");
